"""Schema builder utilities for creating Pydantic models from JSON schemas."""

from datetime import date, datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field, create_model

SIMPLE_TYPES: dict[str, type] = {
    "integer": int,
    "number": float,
    "boolean": bool,
}
DATETIME_FORMATS = ("date-time", "datetime")
LOCAL_REF_PREFIX = "#/$defs/"


def create_pydantic_model_from_json_schema(
    json_schema: dict[str, Any],
    field_options: dict[str, list[str]] | None = None,
    model_name: str = "DynamicModel",
) -> type[BaseModel]:
    """Create a Pydantic model from JSON schema with field options and widgets.

    Converts a JSON schema (as generated by ``model_json_schema()``) back to a
    Pydantic model: ``anyOf`` with ``null`` becomes ``X | None``, string formats
    ``date`` / ``date-time`` map to ``date`` / ``datetime``, and local
    ``#/$defs/...`` references are resolved. Referenced (or inline) ``enum``
    schemas become a dynamically built ``Enum`` (one class per ``$defs`` entry)
    so they render as a selectbox. Recursive ``$defs`` are not supported.

    Required fields stay required (unless the schema gives a ``default``), also
    when they carry ``widget`` / ``kw`` configuration.

    Args:
        json_schema: A dictionary representing the JSON schema
        field_options: Dictionary mapping field names to available options for widgets
        model_name: Name for the dynamically created model

    Returns:
        A dynamically created Pydantic model class
    """
    builder = _SchemaBuilder(json_schema.get("$defs", {}), field_options or {})
    return builder.build_model(json_schema, model_name)


class _SchemaBuilder:
    """Converts JSON schema fragments to Python types, sharing ``$defs``."""

    def __init__(
        self, defs: dict[str, Any], field_options: dict[str, list[str]]
    ) -> None:
        self.defs = defs
        self.field_options = field_options
        self.ref_cache: dict[str, Any] = {}

    def build_model(
        self, json_schema: dict[str, Any], model_name: str
    ) -> type[BaseModel]:
        """Build a Pydantic model from an object schema."""
        required = json_schema.get("required", [])
        fields: dict[str, Any] = {}
        for field_name, field_schema in json_schema.get("properties", {}).items():
            python_type = self.to_type(field_schema, field_name, model_name)
            field_info = self.field_info(
                field_name, field_schema, is_required=field_name in required
            )
            fields[field_name] = (python_type, field_info)
        return create_model(model_name, **fields)

    def field_info(
        self, field_name: str, field_schema: dict[str, Any], is_required: bool
    ) -> Any:
        """Build the ``Field(...)`` with default and widget configuration."""
        widget = field_schema.get("widget")
        kw = dict(field_schema.get("kw", {}))
        if "options" in field_schema:
            kw["options"] = field_schema["options"]
        elif field_name in self.field_options and "options" not in kw:
            kw["options"] = self.field_options[field_name]

        json_schema_extra: dict[str, Any] = {}
        if widget:
            json_schema_extra["widget"] = widget
        if kw:
            json_schema_extra["kw"] = kw

        default = field_schema.get("default", ... if is_required else None)
        return Field(default=default, json_schema_extra=json_schema_extra or None)

    def to_type(self, schema: dict[str, Any], field_name: str, model_name: str) -> Any:
        """Map one JSON schema fragment to a Python type."""
        if "$ref" in schema:
            return self.resolve_ref(schema["$ref"])
        all_of = schema.get("allOf")
        if all_of and len(all_of) == 1:
            return self.to_type(all_of[0], field_name, model_name)
        if "anyOf" in schema:
            options = schema["anyOf"]
            non_null = [s for s in options if s.get("type") != "null"]
            if not non_null:
                return Any
            base_type = self.to_type(non_null[0], field_name, model_name)
            return _optional(base_type) if len(non_null) < len(options) else base_type
        if "enum" in schema:
            return _enum_of(f"{model_name}{field_name.capitalize()}", schema["enum"])

        field_type = schema.get("type")
        if field_type == "string":
            field_format = schema.get("format")
            if field_format == "date":
                return date
            if field_format in DATETIME_FORMATS:
                return datetime
            return str
        if field_type in SIMPLE_TYPES:
            return SIMPLE_TYPES[field_type]
        if field_type == "array":
            if field_name in self.field_options:
                return list[str]
            items = schema.get("items", {})
            return _list_of(self.to_type(items, field_name, f"{model_name}Item"))
        if field_type == "object":
            return self.build_model(schema, f"{model_name}{field_name.capitalize()}")
        return Any

    def resolve_ref(self, ref: str) -> Any:
        """Resolve a local ``#/$defs/Name`` reference, one type per name."""
        if ref in self.ref_cache:
            return self.ref_cache[ref]
        if not ref.startswith(LOCAL_REF_PREFIX):
            msg = f"Only local '{LOCAL_REF_PREFIX}' refs are supported, got {ref!r}"
            raise ValueError(msg)
        name = ref.removeprefix(LOCAL_REF_PREFIX)
        if name not in self.defs:
            msg = f"Unresolvable $ref {ref!r}"
            raise ValueError(msg)
        schema = self.defs[name]
        if "enum" in schema:
            resolved = _enum_of(name, schema["enum"])
        elif schema.get("type") == "object" or "properties" in schema:
            resolved = self.build_model(schema, name)
        else:
            resolved = self.to_type(schema, name, name)
        self.ref_cache[ref] = resolved
        return resolved


def _enum_of(name: str, values: list[Any]) -> Any:
    """Build an ``Enum`` whose member values are the JSON schema enum values.

    Member names are positional (``V0``, ``V1``...) as values may not be identifiers.
    """
    return Enum(name, {f"V{i}": value for i, value in enumerate(values)})


def _list_of(item_type: Any) -> Any:
    """Build ``list[item_type]`` from a type known only at runtime."""
    return list[item_type]


def _optional(base_type: Any) -> Any:
    """Build ``base_type | None`` from a type known only at runtime."""
    return base_type | None
